def create_customer_reply(customer_message):

    message = customer_message.lower()


    if "قیمت" in message or "چنده" in message:

        return """
سلام وقت بخیر 🌹

قیمت محصول بستگی به مدل و شرایط فعلی دارد.
اگر مایل باشید اطلاعات کامل و شرایط خرید را برایتان ارسال می‌کنیم.

در خدمت شما هستیم.
        """



    elif "موجود" in message or "دارید" in message:

        return """
سلام 👋

بله، این محصول موجود است.
برای ثبت سفارش یا دریافت اطلاعات بیشتر در خدمت شما هستیم.
        """



    elif "تخفیف" in message:

        return """
سلام 🌟

برای مشتریان عزیز ممکن است تخفیف‌های ویژه در نظر گرفته شود.
لطفاً محصول مورد نظر را بفرمایید تا بررسی کنیم.
        """



    else:

        return f"""
سلام 👋

از پیام شما ممنونیم.

در مورد:
"{customer_message}"

کارشناسان ما در اسرع وقت راهنمایی لازم را ارائه می‌دهند.
        """
