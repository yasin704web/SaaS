def make_hashtags(field):

    return (
        f"# {field.replace(' ', '_')}\n\n"
        f"#{field.replace(' ', '_')} "
        "#آموزش #محتوا #رشد #اینستاگرام "
        "#تلگرام #تولید_محتوا"
    )


