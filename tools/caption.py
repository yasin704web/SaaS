def make_hook(topic):

    return f"""
⚡ هوک‌های پیشنهادی برای:

{topic}

1️⃣ «قبل از اینکه درباره {topic} تصمیم بگیری، اینو بدون.»

2️⃣ «۹۰٪ افراد درباره {topic} این اشتباه رو می‌کنن.»

3️⃣ «اگه {topic} برات مهمه، این ۳۰ ثانیه رو از دست نده.»

4️⃣ «کاش یکی زودتر این نکته درباره {topic} رو بهم می‌گفت.»

5️⃣ «۳ نکته درباره {topic} که خیلی‌ها نمی‌دونن.»
"""


def make_bio(name, field):

    return f"""
✨ بیو پیشنهادی

{name}
🎯 تخصص در {field}
💡 آموزش | تجربه | نکات کاربردی
🚀 کمک می‌کنم بهتر و حرفه‌ای‌تر پیش بری
📩 ارتباط: دایرکت
"""


def make_content_ideas(field):

    ideas = [
        f"۵ اشتباه رایج در {field}",
        f"۳ نکته کمتر گفته‌شده درباره {field}",
        f"قبل و بعد از یادگیری {field}",
        f"سؤال و جواب درباره {field}",
        f"یک تجربه واقعی درباره {field}",
        f"آموزش سریع {field}",
        f"مقایسه دو روش در {field}",
        f"اشتباهی که تازه‌کارها در {field} انجام می‌دهند",
    ]

    return "💡 ایده‌های محتوا\n\n" + "\n".join(
        f"{i+1}. {x}" for i, x in enumerate(ideas)
    )


